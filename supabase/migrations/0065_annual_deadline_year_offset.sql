-- ============================================================
-- Органайзер — поправка на "Период" за годишните fixed_date
-- задължения, отчитащи ПРЕДХОДНАТА година (поискано 2026-09-02,
-- открито от Дойчин на живо в прогрес-таблицата за ГФО в ТР:
-- срокът е 30.09.2026, но периодът показваше "2026" вместо "2025").
--
-- Причина: periodsForRule('fixed_date') в generate-tasks/index.ts
-- досега винаги слагаше period_label/period_start/period_end =
-- ГОДИНАТА НА ГЕНЕРИРАНЕ (= годината на срока), вместо годината,
-- за която реално се отчита декларацията. Кодът вече поддържа
-- незадължително поле "year_offset" в deadline_rule (виж
-- periodsForRule) — тук го задаваме -1 за деветте задължения,
-- които отчитат предходната календарна година. Останалите fixed_date
-- задължения (патентна декларация, местни данъци, чл.87а авансови
-- вноски, чл.61р ЗМДТ) НЕ се пипат тук — потвърдено изрично от
-- Дойчин, че отчитат текущата година.
--
-- Само занапред генерирани задачи ще ползват новия offset — вече
-- създадените живи редове с грешен период се коригират отделно, с
-- изричен UPDATE (виж чат сесията, не тук — мутиращ service_role
-- SQL по правило).
-- ============================================================

update obligation_types
set deadline_rule = deadline_rule || '{"year_offset": -1}'::jsonb
where code in (
  'gdd_individuals',        -- ГДД физически лица (30 април)
  'gdd_chl50_et',            -- ГДД по чл. 50 ЗДДФЛ (30 юни)
  'gdd_zkpo_92',             -- ГДД по чл. 92 ЗКПО (30 юни)
  'god_nsi',                 -- ГФО пред НСИ (30 юни)
  'gfo_or_chl38',            -- Публикуване на ГФО в ТР, чл. 38 (30 септември)
  'god_nsi_consolidated',    -- ГОД пред НСИ — консолидиран отчет (30 септември)
  'chl73_al1',               -- Справка чл. 73, ал. 1 ЗДДФЛ — наеми/дивиденти (28 февруари)
  'chl73_al6',               -- Справка чл. 73, ал. 6 ЗДДФЛ — ТД (28 февруари)
  'sol_obr6_annual'          -- Годишен Обр. 6 за СОЛ (30 април)
);
