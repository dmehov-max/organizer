-- със ЕДНАКЪВ created_at до секундата).
--
-- Поправено по образец на другите истински "по събитие" типове
-- (майчинство, чл.88 ЗКПО) — {"type":"manual"}.
-- ============================================================

update obligation_types
set deadline_rule = '{"type":"manual"}'::jsonb
where code = 'sick_leave' and valid_to is null;
