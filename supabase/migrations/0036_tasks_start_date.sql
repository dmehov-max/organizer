-- Дата, от която да се генерират автоматични задачи за клиента —
-- решава случая "нова фирма получава фантомна задача за стар срок,
-- който реално не дължи" (напр. ГДД по чл.92 ЗКПО за данъчна 2025 г.,
-- генерирана за фирма, регистрирана през 2026 г. — срокът 30.06.2026
-- е само 41 дни назад, под 60-дневния "grace" праг в generate-tasks,
-- но фирмата реално не е съществувала през облагаемата 2025 г.).
--
-- По подразбиране = датата на добавяне в Органайзер (created_at) —
-- разумно, защото повечето клиенти се добавят горе-долу когато
-- реално стават клиенти. Редактируемо в досието за изричните
-- изключения (стара фирма, добавена късно в системата — тогава
-- полето се връща назад, за да хванем реално дължимите стари срокове).
-- ============================================================

alter table clients add column tasks_start_date date;
update clients set tasks_start_date = created_at::date where tasks_start_date is null;
alter table clients alter column tasks_start_date set not null;
alter table clients alter column tasks_start_date set default current_date;
