-- ============================================================
-- Органайзер — корекция на "Период" на ВЕЧЕ СЪЗДАДЕНИТЕ годишни
-- задачи (2026-09-15). Допълва 0065, която оправя само бъдещото
-- генериране. Открито на живо от Дойчин за втори път в прогрес-таблицата
-- "Публикуване на ГФО в ТР": срок 30.09.2026, период "2026" вместо "2025".
--
-- Причина за повторението: 0065 беше комитната на 02.09, но НЕ беше
-- пусната в живата база (проверено на 15.09 — нито едно задължение
-- нямаше year_offset), а корекцията на съществуващите редове,
-- обещана в 0065, така и не беше направена. Затова този файл се пуска
-- ЗАЕДНО с 0065, в една транзакция.
--
-- Идемпотентно: пипа само редове, чийто период все още е равен на
-- годината на срока (т.е. грешният вариант) — второ пускане не прави нищо.
-- Засяга същите девет задължения като 0065.
-- ============================================================

update tasks t
set period_label = (extract(year from t.due_date)::int - 1)::text,
    period_start = make_date(extract(year from t.due_date)::int - 1, 1, 1),
    period_end   = make_date(extract(year from t.due_date)::int - 1, 12, 31)
from obligation_types o
where t.obligation_type_id = o.id
  and o.code in (
    'gdd_individuals', 'gdd_chl50_et', 'gdd_zkpo_92', 'god_nsi', 'gfo_or_chl38',
    'god_nsi_consolidated', 'chl73_al1', 'chl73_al6', 'sol_obr6_annual'
  )
  and t.period_label = extract(year from t.due_date)::int::text;
