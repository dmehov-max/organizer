-- Органайзер — съобщение до КЛИЕНТА от контекста на задача, плюс
-- имейл известяване (поискано 2026-09-21, продължение на 0069).
--
-- Досега имаше две несвързани неща: нишката с клиента (0061), която
-- се отваряше само от досието му и нямаше представа за какво става
-- дума, и вътрешната нишка между служителите (0069), закачена за
-- задача. Счетоводителят обаче най-често иска да напише на клиента
-- точно докато гледа задачата ("нужен е подпис за ГФО до петък").
--
-- Затова client_messages получава същия незадължителен контекст като
-- staff_messages. Празен task_id = както досега, общ разговор от
-- досието; попълнен = съобщение по конкретна задача.
--
-- ВАЖНО за имейла: клиентът НЯМА логин и няма причина да отваря
-- upload.html от само себе си — съобщение, което само стои в базата,
-- на практика не е изпратено. Затова всяко съобщение от нас към
-- клиента тръгва и като имейл до clients.contact_emails (0060), с
-- линк към неговата страница. emailed_at пази кога е станало, за да
-- не се праща втори път и за да се вижда в интерфейса дали е стигнало.
-- ============================================================

alter table client_messages add column if not exists task_id uuid references tasks(id) on delete set null;
alter table client_messages add column if not exists context_label text;
alter table client_messages add column if not exists emailed_at timestamptz;

create index if not exists idx_client_messages_task on client_messages(task_id, created_at)
  where task_id is not null;

