-- ============================================================
-- "+ Задача по събитие" гърмеше с RLS грешка за счетоводител, ако
-- клиентът не е негов (tasks_insert изискваше is_client_owner()) —
-- открито на живо 2026-08-18, веднага след като 0043/0044 вече им
-- дадоха достъп да ВИЖДАТ/редактират всички клиенти.
--
-- Не стига само "assigned_user_id = auth.uid()" — формата за задача
-- по събитие (index.html, openNewEventTaskModal) назначава задачата
-- на РЕАЛНИЯ отговорник на клиента (client.responsible_user_id), не
-- задължително на човека, който попълва формата (напр. Нерман логва
-- болничен на клиент на Дойчин). Затова тук се маха и това условие —
-- всеки активен потребител може да създаде задача за всеки клиент,
-- назначена на когото и да е, в синхрон с 0043/0044.
-- ============================================================

drop policy if exists tasks_insert on tasks;
create policy tasks_insert on tasks
  for insert to authenticated
  with check (is_admin() or is_active());
